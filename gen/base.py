def _load_ref():
    with open(REF_PATH, encoding='utf-8') as f:
        return f.read()


def parse_reference():
    """Возвращает dict: '1.1' -> (heading, body)."""
    txt = _load_ref()
    blocks = {}
    cur = None
    buf = []
    for line in txt.split('\n'):
        m = re.match(r'^### (\d+\.\d+) (.+)$', line)
        if m:
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur = m.group(1)
            blocks[cur] = (line, '')
            buf = []
        elif re.match(r'^## |^### ', line):
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur = None
            buf = []
        elif cur:
            buf.append(line)
    if cur:
        blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
    return blocks


REF = parse_reference()


