def table_of_duties(rows):
    out = ['---', '', '## ПРИЛОЖЕНИЕ №2', '',
           '### Перечень инструкций по охране труда, действующих в организации', '',
           '| Обозначение | Наименование | Должности (виды работ) |', '|---|---|---|']
    for r in rows:
        out.append('| ' + ' | '.join(r) + ' |')
    return '\n'.join(out) + '\n'


def assemble(parts, overrides):
    """Собирает документ: общие блоки из эталона + переопределения.

    parts      — список ключей блоков в нужном порядке
    overrides  — dict: ключ блока -> готовый текст блока (вместе с заголовком)
    """
    out = []
    for key in parts:
        if key in overrides:
            out.append(overrides[key].rstrip('\n'))
        else:
            heading, body = REF[key]
            out.append((heading + '\n\n' + body).rstrip('\n'))
    return '\n\n'.join(out)


def render(section_no, key, body):
    """Собирает блок с заголовком из эталона и новым телом."""
    heading = REF[key][0]
    return heading + '\n\n' + body.rstrip('\n')
