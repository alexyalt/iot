def build(spec, filename):
    L = [header(spec['title'], spec.get('sub'), spec['positions'], spec['code'])]
    for n in ('1', '2', '3', '4', '5', '6'):
        key = 'sec' + n
        if key in spec:
            L.append(SEC[n])
            L.append(spec[key].strip('\n'))
    L.append(spec.get('appendix') or appendix(spec['positions']))
    content = '\n\n'.join(x for x in L if x) + '\n'
    path = os.path.join(OUT, filename)
    open(path, 'w', encoding='utf-8').write(content)
    return path, len(content)
