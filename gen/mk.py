def header(title, sub, positions, code):
    L = ['# ИНСТРУКЦИЯ ПО ОХРАНЕ ТРУДА', '', '## ' + title, '']
    if sub:
        L += [sub, '']
    L += ['**Организация:** ' + ORG, '', '**Обозначение:** ' + code, '',
          '**Распространяется на должности:** ' + '; '.join(positions) + '.', '',
          '**Дата утверждения:** ' + DATE, '', '**Действительна с:** ' + DATE, '',
          '---', '']
    return '\n'.join(L)


