def _parse():
    txt = open(REF_PATH, encoding='utf-8').read()
    blocks, cur, buf = {}, None, []
    for line in txt.split('\n'):
        m = re.match(r'^### (\d+\.\d+) ', line)
        if m:
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur, buf = m.group(1), []
            blocks[cur] = (line, '')
        elif re.match(r'^## |^### |^# ', line):
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur, buf = None, []
        elif cur:
            buf.append(line)
    if cur:
        blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
    return blocks


REF = _parse()


def verbatim(key):
    """Блок эталона без изменений."""
    h, b = REF[key]
    return h + '\n\n' + b


def retitle(key, new_heading, body=None):
    h, b = REF[key]
    return '### ' + new_heading + '\n\n' + (b if body is None else body)


