def b13(term_name, term_def, extra=()):
    body = REF['1.3'][1]
    body = re.sub(r'\n*1\.3\.6 \*\*Садовник.*?(?=\n\n|$)', '', body, flags=re.S).rstrip()
    out = ['### 1.3 Термины и определения', '', body, '',
           f'1.3.6 **{term_name}** — {term_def}']
    for i, (n, d) in enumerate(extra, 7):
        out += ['', f'1.3.{i} **{n}** — {d}']
    return '\n'.join(out)


