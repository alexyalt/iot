# --------------------------------------------------------------- сборка

def make(spec):
    """spec: title, sub, code, labels, kind, sec1..sec6, appendix_note."""
    L = ['# ИНСТРУКЦИЯ ПО ОХРАНЕ ТРУДА', '', '## ' + spec['title'], '']
    if spec.get('sub'):
        L += [spec['sub'], '']
    L += ['**Организация:** ' + ORG, '', '**Обозначение:** ' + spec['code'], '',
          '**Распространяется на:** ' + '; '.join(spec['labels']) + '.', '',
          '**Дата утверждения:** ' + DATE, '', '**Действительна с:** ' + DATE, '',
          '---', '']
    body = '\n'.join(L)
    parts = []
    for n in range(1, 7):
        if spec.get(f'sec{n}'):
            if n > 1:
                parts.append('---')
            parts.append(SEC_TITLES[n])
            parts.append(spec[f'sec{n}'].strip('\n'))
    parts.append(spec.get('appendix') or appendix(
        spec['labels'], spec.get('kind', 'Должность')))
    body += '\n' + '\n\n'.join(parts) + '\n'
    path = os.path.join(OUT_DIR, spec['filename'])
    open(path, 'w', encoding='utf-8').write(body)
    return path, len(body)


def std_sec2(check_ws, check_tool, weather=True):
    out = ['### 2.1 Проверка рабочего места\n\n' + check_ws.strip(),
           '### 2.2 Проверка инструмента и оборудования\n\n' + check_tool.strip(),
           vb('2.3'), vb('2.4')]
    if weather:
        out.append(vb('2.5'))
    return '\n\n'.join(out)


# ------------------------------------------------------------ универсальная

def doc(filename, code, title, labels, kind, role_name, role_def, extra_terms,
        hazards_intro, hazard_blocks, ppe_extra, sec2_ws, sec2_tool,
        sec3, sec5_close, sec5_extra=None, weather=True, appendix_note=None):
    """Собирает инструкцию с единой структурой разделов 1-6."""
    sec1 = '\n\n'.join([
        b11('должностях' if kind == 'Должность' else 'работах',
            '«' + '», «'.join(labels) + '»'),
        vb('1.2'),
        b13(role_name, role_def, extra_terms),
        b14s(hazards_intro, hazard_blocks),
        vb('1.5'),
        b16('соответствующей должности' if kind == 'Должность'
            else 'соответствующего вида работ', labels, ppe_extra),
    ])
    sec2 = std_sec2(sec2_ws, sec2_tool, weather)
    ex = sec5_extra or {}
    sec5 = b5(sec5_close, ex.get('hand'), ex.get('ppe'), ex.get('clean'), ex.get('hyg'))
    spec = {
        'filename': filename, 'code': code, 'title': title, 'labels': labels,
        'kind': kind, 'sec1': sec1, 'sec2': sec2, 'sec3': sec3,
        'sec4': b4(), 'sec5': sec5, 'sec6': vb('6.1') + '\n\n' + vb('6.2'),
    }
    if appendix_note:
        spec['appendix'] = appendix_note
    return make(spec)
