DATE = '16 ноября 2026 г.'


def _parse_ref():
    txt = open(REF_PATH, encoding='utf-8').read()
    blocks, cur, buf = {}, None, []
    for line in txt.split('\n'):
        m = re.match(r'^### (\d+\.\d+) ', line)
        if m:
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur, buf = m.group(1), []
            blocks[cur] = (line, '')
        elif re.match(r'^## |^### |^# ', line):
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur, buf = None, []
        elif cur:
            buf.append(line)
    if cur:
        blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
    for k, (h, b) in blocks.items():
        b = re.sub(r'\n*---\s*$', '', b).rstrip()
        blocks[k] = (h, b)
    return blocks


REF = _parse_ref()

