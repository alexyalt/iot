"""Движок сборки инструкций по охране труда на базе эталона «Садовник»."""
import re, os

REF_PATH = '/tmp/iot/iotv2/Инструкция_по_охране_труда_Садовник.md'
OUT_DIR = '/tmp/iot/iotv2'
ORG = 'ООО "Слайс ЛТД"'
DATE = '16 ноября 2026 г.'


def parse_reference():
    txt = open(REF_PATH, encoding='utf-8').read()
    blocks, cur, buf = {}, None, []
    for line in txt.split('\n'):
        m = re.match(r'^### (\d+\.\d+) ', line)
        if m:
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur = m.group(1)
            blocks[cur] = (line, '')
            buf = []
        elif re.match(r'^## |^### |^# ', line):
            if cur:
                blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
            cur, buf = None, []
        elif cur:
            buf.append(line)
    if cur:
        blocks[cur] = (blocks[cur][0], '\n'.join(buf).strip('\n'))
    return blocks


REF = parse_reference()

