def build(spec):
    """spec: dict с ключами title, subtitle, positions, code, sec1..sec5, appendix."""
    L = []
    L += ['# ИНСТРУКЦИЯ ПО ОХРАНЕ ТРУДА', '', f'## {spec["title"]}', '']
    if spec.get('subtitle'):
        L += [spec['subtitle'], '']
    L += [f'**Организация:** {ORG}', '']
    if spec.get('code'):
        L += [f'**Обозначение:** {spec["code"]}', '']
    L += [f'**Распространяется на должности:** {"; ".join(spec["positions"])}.', '',
          f'**Дата утверждения:** {DATE}', '',
          f'**Действительна с:** {DATE}', '', '---', '']
    body = '\n'.join(L)

    parts = []
    for n in ('1', '2', '3', '4', '5', '6'):
        key = 'sec' + n
        if key not in spec:
            continue
        parts.append(SEC_TITLES[n])
        parts.append(spec[key].strip('\n'))
    body += '\n' + '\n\n'.join(parts) + '\n\n'
    body += spec.get('appendix', appendix_stub(spec['positions']))
    return body


def write(spec, filename):
    content = build(spec)
    path = os.path.join(OUT_DIR, filename)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    return path, len(content)
